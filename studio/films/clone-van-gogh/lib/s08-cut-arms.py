"""Cuts a generated full-figure cut-out into rig parts: torso (with a short shoulder stub) plus, per arm,
an upper arm and a forearm+hand, each cropped to its bounds. Writes assets/gen/<fig>-<part>.png and
lib/<fig>-parts.ts (hinge pivots and figure-space origins for src/rig). Run from the film folder:
  python3 -I lib/s08-cut-arms.py
Arm geometry (shoulder S, elbow E, hand tip H, half-widths) is read off a 100 px grid overlay of the figure."""
import math, os
from PIL import Image, ImageDraw, ImageFilter

SS = 3
FIGS = {
    # fig: (source cut-out, arms)
    "s08b-gauguin": ("assets/gen/s08b-gauguin-cut.png", {
        "l": dict(S=(345, 378), E=(225, 345), H=(15, 240), ru=58, rf=48, stub=34),
        "r": dict(S=(575, 410), E=(655, 500), H=(695, 590), ru=52, rf=44, stub=34),
    }),
    "s08b-vg": ("assets/gen/s08b-vg-cut.png", {
        "l": dict(S=(300, 450), E=(185, 480), H=(60, 310), ru=56, rf=44, stub=34),
        "r": dict(S=(540, 450), E=(640, 610), H=(715, 725), ru=54, rf=44, stub=34),
    }),
}
import json, sys
if os.path.exists("lib/s13-arms.json"):
    for k, v in json.load(open("lib/s13-arms.json")).items():
        FIGS[k] = (v["src"], {a: {kk: (tuple(vv) if isinstance(vv, list) else vv) for kk, vv in d.items()} for a, d in v["arms"].items()})

def capsule(draw, a, b, ra, rb, s=SS):
    ang = math.atan2(b[1] - a[1], b[0] - a[0])
    nx, ny = -math.sin(ang), math.cos(ang)
    pts = [((a[0] + nx * ra) * s, (a[1] + ny * ra) * s), ((b[0] + nx * rb) * s, (b[1] + ny * rb) * s),
           ((b[0] - nx * rb) * s, (b[1] - ny * rb) * s), ((a[0] - nx * ra) * s, (a[1] - ny * ra) * s)]
    draw.polygon(pts, fill=255)
    for c, r in ((a, ra), (b, rb)):
        draw.ellipse(((c[0] - r) * s, (c[1] - r) * s, (c[0] + r) * s, (c[1] + r) * s), fill=255)

def along(a, b, d):
    L = math.hypot(b[0] - a[0], b[1] - a[1])
    return (a[0] + (b[0] - a[0]) / L * d, a[1] + (b[1] - a[1]) / L * d)

def mask(size, fn):
    m = Image.new("L", (size[0] * SS, size[1] * SS), 0)
    fn(ImageDraw.Draw(m))
    return m.resize(size, Image.LANCZOS)

def mul(a, b):
    return Image.composite(a, Image.new("L", a.size, 0), b)

def save_part(img, m, name, fig, hinge, out):
    alpha = mul(img.getchannel("A"), m)
    part = img.copy(); part.putalpha(alpha)
    bb = alpha.point(lambda v: 255 if v > 8 else 0).getbbox()
    pad = 3
    bb = (max(0, bb[0] - pad), max(0, bb[1] - pad), min(img.width, bb[2] + pad), min(img.height, bb[3] + pad))
    part.crop(bb).save(f"assets/gen/{fig}-{name}.png")
    out[name] = dict(origin=[bb[0], bb[1]], pivot=[round(hinge[0] - bb[0], 1), round(hinge[1] - bb[1], 1)], size=[bb[2] - bb[0], bb[3] - bb[1]])

for fig, (src, arms) in FIGS.items():
    img = Image.open(src).convert("RGBA")
    out = {}
    torso_a = img.getchannel("A")
    for side, g in arms.items():
        S, E, H = g["S"], g["E"], g["H"]
        Hx = along(E, H, math.hypot(H[0] - E[0], H[1] - E[1]) + 22)
        S2 = along(S, E, g["stub"])
        ua = mask(img.size, lambda d: capsule(d, S, E, g["ru"], g["rf"] + 4))
        ex = [tuple(map(tuple, e[:2])) + tuple(e[2:]) for e in g.get("extra", [])]  # extra capsules of the forearm (a, b, ra, rb): brush, fingers
        def fa_shape(d, grow=0):
            capsule(d, E, Hx, g["rf"] + grow, g["rf"] + 4 + grow)
            for a, b, ra, rb in ex:
                capsule(d, a, b, ra + grow, rb + grow)
        fa = mask(img.size, lambda d: fa_shape(d))
        cut = mask(img.size, lambda d: (capsule(d, S2, E, g["ru"] + 3, g["rf"] + 6), fa_shape(d, 4)))
        torso_a = Image.composite(Image.new("L", img.size, 0), torso_a, cut.point(lambda v: 255 if v > 127 else 0))
        # the upper arm stops short of the forearm's disc so the forearm (drawn on top) owns the elbow
        save_part(img, ua, f"ua_{side}", fig, S, out)
        save_part(img, fa, f"fa_{side}", fig, E, out)
    torso = img.copy(); torso.putalpha(torso_a)
    bb = torso_a.point(lambda v: 255 if v > 8 else 0).getbbox()
    torso.save(f"assets/gen/{fig}-torso.png")
    out["torso"] = dict(origin=[0, 0], pivot=[img.width // 2, 1000 if img.height > 1200 else img.height // 2], size=list(img.size))
    with open(f"lib/{fig}-parts.ts", "w") as f:
        f.write("// generated by lib/s08-cut-arms.py\nexport const PARTS = " + json.dumps(out, indent=1) + " as const;\n")
    print(fig, "ok")
