#!/usr/bin/env python3
"""Composes motion-measure's per-frame camera steps into a cumulative camera table (TypeScript).

  camera-table.py <frames.csv> --from A --to B --out table.ts [--cut F ...] [--export NAME]

<frames.csv> is motion-measure.py's per-frame output. The range is [A, B) in the reference's frame
numbers (the same from/to a scene list uses): row 0 of the table is frame A, the identity; row k is
frame A+k. Every row of frames.csv holds the step "frame-1 -> frame" as (scale, tx, ty), with tx/ty
the move of the frame centre in native px. A step is held (identity: the pose does not move) when
its method is ecc or none (the tracker failed), or "first", or when --cut names that frame (a cut:
the picture changed, so no camera motion links it to the one before).

Composition about the frame centre c, step p' = s (p - c) + c + m on top of the pose S, T:
  S' = s S        T' = s T + m
The output module exports `TABLE: [scale, tx, ty][]`, the shape src/camera/table.ts reads.

Run with: /Users/guisfits/llm-models/venv_mlx/bin/python -I tools/critique/camera-table.py ...
"""

import argparse
import csv
import sys
from pathlib import Path

import numpy as np

# Steps from these methods are not camera measurements: the pose holds.
HOLD_METHODS = {"ecc", "none", "first"}
SCALE_DECIMALS = 5
TRANSLATION_DECIMALS = 2


def read_steps(path):
    """Returns {frame: (method, scale, tx, ty)} from a motion-measure frames.csv."""
    steps = {}
    with open(path, newline="") as fh:
        for row in csv.DictReader(fh):
            steps[int(row["frame"])] = (
                row["method"],
                float(row["scale"]),
                float(row["tx"]),
                float(row["ty"]),
            )
    return steps


def compose(steps, start, end, cuts=()):
    """Cumulative [scale, tx, ty] per frame of [start, end); row 0 is the identity."""
    if end <= start:
        raise ValueError(f"empty range [{start}, {end})")
    missing = [f for f in range(start + 1, end) if f not in steps]
    if missing:
        raise ValueError(f"frames.csv has no row for frame {missing[0]}")
    cut_set = set(cuts)
    pose = np.array([1.0, 0.0, 0.0])
    table = [pose.copy()]
    for f in range(start + 1, end):
        method, s, mx, my = steps[f]
        if method not in HOLD_METHODS and f not in cut_set:
            pose = np.array([s * pose[0], s * pose[1] + mx, s * pose[2] + my])
        table.append(pose.copy())
    return np.array(table)


def _fmt(v, decimals):
    text = f"{v:.{decimals}f}"
    return text[1:] if text.startswith("-") and float(text) == 0 else text


def to_ts(table, source, start, end, cuts, export):
    rows = ",\n".join(
        f"  [{_fmt(s, SCALE_DECIMALS)}, {_fmt(x, TRANSLATION_DECIMALS)}, {_fmt(y, TRANSLATION_DECIMALS)}]"
        for s, x, y in table
    )
    cut_note = f", cuts at {', '.join(map(str, sorted(cuts)))}" if cuts else ""
    return (
        f"// Camera table, reference frames {start}..{end - 1} (row k = frame {start}+k, row 0 identity){cut_note}.\n"
        f"// Generated by tools/critique/camera-table.py from {source}; do not edit by hand.\n"
        f"// Each row: cumulative [scale, tx, ty] about the frame centre, tx/ty in native px.\n"
        f"export const {export}: [number, number, number][] = [\n{rows},\n];\n"
    )


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("frames_csv")
    ap.add_argument("--from", dest="start", type=int, required=True)
    ap.add_argument("--to", dest="end", type=int, required=True, help="exclusive")
    ap.add_argument("--out", required=True)
    ap.add_argument("--cut", type=int, action="append", default=[], help="frame whose step is dropped (repeatable)")
    ap.add_argument("--export", default="TABLE")
    args = ap.parse_args(argv)
    try:
        table = compose(read_steps(args.frames_csv), args.start, args.end, args.cut)
    except ValueError as err:
        sys.exit(f"camera-table: {err}")
    Path(args.out).write_text(
        to_ts(table, args.frames_csv, args.start, args.end, args.cut, args.export)
    )
    print(f"{args.out}: {len(table)} rows, final scale {table[-1][0]:.4f}")


if __name__ == "__main__":
    main()
